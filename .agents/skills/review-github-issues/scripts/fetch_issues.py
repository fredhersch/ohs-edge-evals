#!/usr/bin/env python3
"""
fetch_issues.py
Helper utility for the review-github-issues skill.
Fetches open issues from the repository, parses the structured directives
generated by the inline agent feedback widget, and outputs a clean report.
"""

import os
import sys
import json
import re
import urllib.request
import ssl

REPO_OWNER = "fredhersch"
REPO_NAME = "ohs-edge-evals"

def get_token():
    # 1. Environment variable
    if os.environ.get("GITHUB_TOKEN"):
        return os.environ.get("GITHUB_TOKEN")
    if os.environ.get("GH_TOKEN"):
        return os.environ.get("GH_TOKEN")
    
    # 2. Local storage from browser widget if persisted in file, or return None
    return None

def fetch_open_issues(owner=REPO_OWNER, repo=REPO_NAME):
    url = f"https://api.github.com/repos/{owner}/{repo}/issues?state=open&per_page=50"
    headers = {
        "User-Agent": "Antigravity-Issue-Review-Skill/1.0",
        "Accept": "application/vnd.github.v3+json"
    }
    token = get_token()
    if token:
        headers["Authorization"] = f"Bearer {token}"

    req = urllib.request.Request(url, headers=headers)
    
    # Unverified SSL context as fallback for mac local python certs
    ctx = ssl.create_default_context()
    try:
        resp = urllib.request.urlopen(req, timeout=15, context=ctx)
    except Exception:
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        resp = urllib.request.urlopen(req, timeout=15, context=ctx)

    data = json.loads(resp.read().decode("utf-8"))
    # Filter out pull requests
    issues = [item for item in data if "pull_request" not in item]
    return issues

def parse_widget_metadata(body):
    """
    Parses metadata generated by the OHS inline agent feedback widget.
    Extracts Target File, CSS Selector, Element Text, Viewport, and Directive.
    """
    meta = {
        "page": None,
        "selector": None,
        "element_text": None,
        "directive": None,
        "html_snippet": None,
        "category": "General"
    }
    if not body:
        return meta

    # Directive / Instruction
    directive_match = re.search(r"#### 💬 User Instruction\s*>\s*(.*?)(?=\n---|####|$)", body, re.DOTALL)
    if directive_match:
        meta["directive"] = directive_match.group(1).strip()
    elif "**User Request**:" in body:
        m = re.search(r"\*\*User Request\*\*:\s*>\s*(.*?)(?=\n---|###|$)", body, re.DOTALL)
        if m:
            meta["directive"] = m.group(1).strip()

    # Category
    cat_match = re.search(r"\*\*Category\*\*:\s*`([^`]+)`", body)
    if cat_match:
        meta["category"] = cat_match.group(1).strip()

    # Target File
    file_match = re.search(r"- \*\*Target Page / File\*\*:\s*`([^`]+)`", body)
    if file_match:
        meta["page"] = file_match.group(1).strip()
    else:
        file_match2 = re.search(r"- \*\*File / Page\*\*:\s*`([^`]+)`", body)
        if file_match2:
            meta["page"] = file_match2.group(1).strip()

    # CSS Selector
    sel_match = re.search(r"- \*\*CSS Selector\*\*:\s*`([^`]+)`", body)
    if sel_match:
        meta["selector"] = sel_match.group(1).strip()

    # Element Text
    text_match = re.search(r"- \*\*Element Text\*\*:\s*`([^`]+)`", body)
    if text_match:
        meta["element_text"] = text_match.group(1).strip()

    # HTML Snippet
    snippet_match = re.search(r"```html\s*(.*?)\s*```", body, re.DOTALL)
    if snippet_match:
        meta["html_snippet"] = snippet_match.group(1).strip()

    return meta

def main():
    try:
        issues = fetch_open_issues()
    except Exception as e:
        print(f"Error fetching issues: {e}", file=sys.stderr)
        sys.exit(1)

    if not issues:
        print("No open issues found on repository. Everything is up to date! 🎉")
        return

    print(f"Found {len(issues)} open issue(s) on {REPO_OWNER}/{REPO_NAME}:\n")
    print("=" * 80)

    for i, issue in enumerate(issues, 1):
        num = issue["number"]
        title = issue["title"]
        url = issue["html_url"]
        body = issue.get("body", "")
        meta = parse_widget_metadata(body)

        print(f"[{i}] Issue #{num}: {title}")
        print(f"    URL:      {url}")
        print(f"    Category: {meta['category']}")
        if meta["page"]:
            print(f"    Target:   {meta['page']}")
        if meta["selector"]:
            print(f"    Selector: {meta['selector']}")
        if meta["element_text"] and meta["element_text"] != "N/A":
            print(f"    Text:     \"{meta['element_text']}\"")
        if meta["directive"]:
            print(f"    Action:   {meta['directive']}")
        else:
            first_lines = "\n              ".join(body.strip().split("\n")[:4])
            print(f"    Body:     {first_lines}")
        print("-" * 80)

if __name__ == "__main__":
    main()
